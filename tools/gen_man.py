"""Generate docs/man/packagingonlinux.1 from the command line parser, so that the man page
always matches `packagingonlinux --help`.

    python3 tools/gen_man.py           # rewrite the page
    python3 tools/gen_man.py --check   # exit 1 if the page is out of date

tests/test_man.py fails when the page is out of date: run this after changing the CLI,
a backend's label, tools or install hint, or the formats list.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from packagingonlinux import cli  # noqa: E402

PAGE = ROOT / "docs/man/packagingonlinux.1"


def esc(text: str) -> str:
    """Escape text for roff: backslashes, hyphens (so options copy-paste as ASCII '-'),
    and a leading '.' or "'" that would start a request."""
    text = text.replace("\\", "\\e").replace("-", "\\-")
    return "\n".join("\\&" + line if line[:1] in (".", "'") else line for line in text.split("\n"))


def _subcommands(parser: argparse.ArgumentParser) -> list[tuple[str, str, argparse.ArgumentParser]]:
    action = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    summaries = {a.dest: a.help for a in action._choices_actions}
    return [(name, summaries[name], sub) for name, sub in action.choices.items()]


def _options(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in parser._actions if not isinstance(a, argparse._HelpAction)]


def _synopsis(name: str, parser: argparse.ArgumentParser) -> str:
    parts = [f"\\fBpackagingonlinux {name}\\fR"]
    for a in _options(parser):
        if a.option_strings:
            opt = f"\\fB{esc(a.option_strings[0])}\\fR"
            if a.nargs != 0:
                opt += f" \\fI{esc(a.metavar or a.dest.upper())}\\fR"
            parts.append(f"[{opt}]")
        else:
            arg = f"\\fI{esc(a.metavar or a.dest)}\\fR"
            parts.append(f"[{arg}]" if a.nargs == "?" else arg)
    return " ".join(parts)


def _option_item(a: argparse.Action) -> list[str]:
    if a.option_strings:
        names = ", ".join(f"\\fB{esc(o)}\\fR" for o in a.option_strings)
        if a.nargs != 0:
            names += f" \\fI{esc(a.metavar or a.dest.upper())}\\fR"
    else:
        names = f"\\fI{esc(a.metavar or a.dest)}\\fR"
    return [".TP", names, esc(a.help or "")]


def _paragraphs(text: str) -> list[str]:
    out = []
    for para in text.strip().split("\n\n"):
        out += [".PP", esc(" ".join(para.split()))]
    return out


def _table(rows: list[tuple[str, str]], bold: bool = True) -> list[str]:
    out = []
    for key, value in rows:
        out += [".TP", f"\\fB{esc(key)}\\fR" if bold else esc(key), esc(value)]
    return out


def render() -> str:
    parser = cli.build_parser()
    lines = [
        '.\\" Generated by tools/gen_man.py from packagingonlinux/cli.py: do not edit.',
        '.TH PACKAGINGONLINUX 1 "" "PackagingOnLinux" "User Commands"',
        ".SH NAME",
        f"packagingonlinux \\- package a prebuilt application as {esc(', '.join(cli.BACKENDS))}",
        ".SH SYNOPSIS",
        "\\fBpackagingonlinux\\fR \\fICOMMAND\\fR [\\fIOPTIONS\\fR]",
        ".br",
        "\\fBpackagingonlinux\\fR \\fB\\-\\-help\\fR | \\fB\\-\\-version\\fR",
        ".SH DESCRIPTION",
        *_paragraphs(cli.DESCRIPTION),
        ".PP",
        "Every command also accepts \\fB\\-h\\fR, \\fB\\-\\-help\\fR.",
        ".SH COMMANDS",
    ]
    for name, help_text, sub in _subcommands(parser):
        lines += [
            f".SS {name}",
            _synopsis(name, sub),
            ".PP",
            esc(sub.description or help_text),
        ]
        for a in _options(sub):
            lines += _option_item(a)
    lines += [".SH FORMATS", "Values accepted by \\fB\\-f\\fR and by [output] formats."]
    for name, text, hint in cli.formats_help():
        lines += [".TP", f"\\fB{esc(name)}\\fR", esc(text + ".")]
        if hint:
            lines += [".br", "Install: " + esc(hint)]
    lines += [".SH EXIT STATUS", *_table(cli.EXIT_STATUS)]
    lines += [".SH ENVIRONMENT", *_table(cli.ENVIRONMENT)]
    lines += [".SH FILES", *_table(cli.FILES, bold=False)]
    lines += [".SH EXAMPLES"]
    for cmd, what in cli.EXAMPLES:
        lines += [".TP", f"\\fB{esc(cmd)}\\fR", esc(what[:1].upper() + what[1:] + ".")]
    lines += [".SH SEE ALSO", ".BR packaging.toml (5)"]
    return "\n".join(lines) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    page = render()
    if check:
        if not PAGE.is_file() or PAGE.read_text(encoding="utf-8") != page:
            print(f"{PAGE.relative_to(ROOT)} is out of date: run python3 tools/gen_man.py", file=sys.stderr)
            return 1
        return 0
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(page, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

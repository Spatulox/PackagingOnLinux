"""Windows installer (setup.exe) generated with NSIS, which runs natively on Linux.

The installer is per-user: it installs into %LOCALAPPDATA%\\Programs\\<Name> without
asking for administrator rights (no UAC prompt), like VS Code's user installer. All its
registry keys are under HKCU, so there is no 32/64-bit Program Files or registry split.
"""

from __future__ import annotations

import os
import re
import shutil
from pathlib import Path, PurePosixPath

from packagingonlinux import winstage
from packagingonlinux.backends.base import Backend, BuildContext
from packagingonlinux.config import AppSpec
from packagingonlinux.runner import run

UNINSTALLER = "uninstall.exe"

# arch -> (English, French) description of the Windows it needs
_WINDOWS_KIND = {
    "x86": ("Windows", "Windows"),
    "x64": ("64-bit Windows (x64)", "Windows 64 bits (x64)"),
    "arm64": ("Windows on ARM (arm64)", "Windows sur ARM (arm64)"),
}


def esc(text: str) -> str:
    """Escape text for use inside a double-quoted NSIS string."""
    return (text.replace("$", "$$").replace('"', '$\\"')
            .replace("\r", "$\\r").replace("\n", "$\\n").replace("\t", "$\\t"))


def q(text: str) -> str:
    return f'"{esc(text)}"'


def win(rel: str) -> str:
    """POSIX relative path -> Windows separators."""
    return rel.replace("/", "\\")


def product_version(version: str) -> str:
    """The four numbers Windows expects in file properties (1.2.3 -> 1.2.3.0)."""
    numbers = [min(int(n), 65535) for n in re.findall(r"\d+", version.split("+")[0])[:4]]
    return ".".join(str(n) for n in numbers + [0] * (4 - len(numbers)))


def shortcut_name(name: str) -> str:
    """The app name without the characters Windows forbids in file names."""
    return re.sub(r'[<>:"/\\|?*\x00-\x1f]', "", name).strip(" .") or "App"


def publisher(spec: AppSpec) -> str:
    return spec.maintainer.split("<")[0].strip() or spec.name


def nsis_script(spec: AppSpec, payload: dict[str, Path], icon: Path | None, out: Path,
                arch: str, size_kib: int) -> str:
    """Render the .nsi script.

    `payload` maps each installed file (relative POSIX path) to its source on disk. The
    sources must have plain names: makensis takes File source paths literally ($ can't be
    escaped there), so the real name is given with /oname, where escaping works.
    """
    files = list(payload)
    exe = win(winstage.exe_path(spec))
    icon_rel = win(winstage.icon_name(spec)) if icon else exe
    lnk = shortcut_name(spec.name)
    uninst_key = f"Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\{spec.id}"
    app_key = f"Software\\{spec.id}"
    inst = lambda rel: f'"$INSTDIR\\{esc(win(rel))}"'  # noqa: E731

    lines = [
        "; Generated by PackagingOnLinux. Compile with: makensis -INPUTCHARSET UTF8 <this file>",
        "Unicode true",
        "ManifestDPIAware true",
        "SetCompressor /SOLID lzma",
        "RequestExecutionLevel user",
        f"Name {q(spec.name)}",
        f"OutFile {q(str(out))}",
        f'InstallDir "$LOCALAPPDATA\\Programs\\{esc(spec.file_stem)}"',
        f"InstallDirRegKey HKCU {q(app_key)} \"InstallDir\"",
        "",
        '!include "MUI2.nsh"',
        '!include "LogicLib.nsh"',
        '!include "x64.nsh"',
        "!define MUI_ABORTWARNING",
    ]
    if icon:
        icon_src = q(str(icon))
        lines += [f"!define MUI_ICON {icon_src}", f"!define MUI_UNICON {icon_src}"]
    lines += [
        f"!define MUI_FINISHPAGE_RUN {inst(winstage.exe_path(spec))}",
        '!define MUI_FINISHPAGE_SHOWREADME ""',
        "!define MUI_FINISHPAGE_SHOWREADME_NOTCHECKED",
        '!define MUI_FINISHPAGE_SHOWREADME_TEXT "$(DesktopShortcut)"',
        "!define MUI_FINISHPAGE_SHOWREADME_FUNCTION CreateDesktopShortcut",
        "!insertmacro MUI_PAGE_DIRECTORY",
        "!insertmacro MUI_PAGE_INSTFILES",
        "!insertmacro MUI_PAGE_FINISH",
        "!insertmacro MUI_UNPAGE_CONFIRM",
        "!insertmacro MUI_UNPAGE_INSTFILES",
        # The first language is the fallback; Windows' display language is picked if listed.
        '!insertmacro MUI_LANGUAGE "English"',
        '!insertmacro MUI_LANGUAGE "French"',
        'LangString DesktopShortcut ${LANG_ENGLISH} "Create a desktop shortcut"',
        'LangString DesktopShortcut ${LANG_FRENCH} "Créer un raccourci sur le bureau"',
        f'LangString WrongArch ${{LANG_ENGLISH}} "{esc(spec.name)} needs {_WINDOWS_KIND[arch][0]}."',
        f'LangString WrongArch ${{LANG_FRENCH}} "{esc(spec.name)} nécessite {_WINDOWS_KIND[arch][1]}."',
        "",
        f'VIProductVersion "{product_version(spec.version)}"',
        f'VIAddVersionKey /LANG=${{LANG_ENGLISH}} "ProductName" {q(spec.name)}',
        f'VIAddVersionKey /LANG=${{LANG_ENGLISH}} "ProductVersion" {q(spec.version)}',
        f'VIAddVersionKey /LANG=${{LANG_ENGLISH}} "FileVersion" {q(spec.version)}',
        f'VIAddVersionKey /LANG=${{LANG_ENGLISH}} "FileDescription" {q(spec.name + " installer")}',
        f'VIAddVersionKey /LANG=${{LANG_ENGLISH}} "CompanyName" {q(publisher(spec))}',
        f'VIAddVersionKey /LANG=${{LANG_ENGLISH}} "LegalCopyright" {q(spec.license)}',
        "",
        "Function .onInit",
    ]
    arch_check = {"x64": "${RunningX64}", "arm64": "${IsNativeARM64}"}.get(arch)
    if arch_check:
        lines += [
            f"  ${{IfNot}} {arch_check}",
            '    MessageBox MB_ICONSTOP "$(WrongArch)" /SD IDOK',
            "    Abort",
            "  ${EndIf}",
        ]
    lines += ["FunctionEnd", "", 'Section "Install"']

    # Files, grouped by folder (File writes into the current SetOutPath).
    by_dir: dict[str, list[str]] = {}
    for rel in files:
        by_dir.setdefault(PurePosixPath(rel).parent.as_posix(), []).append(rel)
    for folder, names in sorted(by_dir.items()):
        lines.append('  SetOutPath "$INSTDIR"' if folder == "." else f"  SetOutPath {inst(folder)}")
        lines += [f'  File "/oname={esc(PurePosixPath(rel).name)}" {q(str(payload[rel]))}' for rel in names]
    lines += [
        '  SetOutPath "$INSTDIR"',  # working directory of the shortcuts
        f'  WriteUninstaller "$INSTDIR\\{UNINSTALLER}"',
        f'  CreateShortcut "$SMPROGRAMS\\{esc(lnk)}.lnk" {inst(winstage.exe_path(spec))} "" '
        f'"$INSTDIR\\{esc(icon_rel)}" 0',
        f'  WriteRegStr HKCU {q(app_key)} "InstallDir" "$INSTDIR"',
    ]
    reg = [
        ("DisplayName", q(spec.name)),
        ("DisplayVersion", q(spec.version)),
        ("Publisher", q(publisher(spec))),
        ("DisplayIcon", f'"$INSTDIR\\{esc(icon_rel)}"'),
        ("InstallLocation", '"$INSTDIR"'),
        ("UninstallString", f'"$\\"$INSTDIR\\{UNINSTALLER}$\\""'),
        ("QuietUninstallString", f'"$\\"$INSTDIR\\{UNINSTALLER}$\\" /S"'),
    ]
    if spec.homepage:
        reg.append(("URLInfoAbout", q(spec.homepage)))
    lines += [f"  WriteRegStr HKCU {q(uninst_key)} {q(k)} {v}" for k, v in reg]
    lines += [
        f'  WriteRegDWORD HKCU {q(uninst_key)} "EstimatedSize" {size_kib}',
        f'  WriteRegDWORD HKCU {q(uninst_key)} "NoModify" 1',
        f'  WriteRegDWORD HKCU {q(uninst_key)} "NoRepair" 1',
        "SectionEnd",
        "",
        "Function CreateDesktopShortcut",
        '  SetOutPath "$INSTDIR"',
        f'  CreateShortcut "$DESKTOP\\{esc(lnk)}.lnk" {inst(winstage.exe_path(spec))} "" '
        f'"$INSTDIR\\{esc(icon_rel)}" 0',
        "FunctionEnd",
        "",
        'Section "Uninstall"',
    ]
    # Remove exactly what was installed, never "RMDir /r $INSTDIR": the user may have
    # picked a folder that holds other files.
    lines += [f"  Delete {inst(rel)}" for rel in files]
    lines.append(f'  Delete "$INSTDIR\\{UNINSTALLER}"')
    folders = {p.as_posix() for rel in files for p in PurePosixPath(rel).parents if p.as_posix() != "."}
    lines += [f"  RMDir {inst(d)}" for d in sorted(folders, key=lambda d: (-d.count("/"), d))]
    lines += [
        '  RMDir "$INSTDIR"',
        f'  Delete "$SMPROGRAMS\\{esc(lnk)}.lnk"',
        f'  Delete "$DESKTOP\\{esc(lnk)}.lnk"',
        f"  DeleteRegKey HKCU {q(uninst_key)}",
        f"  DeleteRegKey HKCU {q(app_key)}",
        "SectionEnd",
    ]
    return "\n".join(lines) + "\n"


def _link_or_copy(src: Path, dest: Path) -> None:
    try:
        os.link(src, dest)
    except OSError:
        shutil.copy2(src, dest)


class NsisBackend(Backend):
    name = "nsis"
    label = "Windows installer (setup.exe)"
    platform = "windows"
    required_tools = ("makensis",)
    install_hint = "apt install nsis  |  dnf install mingw32-nsis  |  pacman -S nsis (AUR)"

    def build(self, ctx: BuildContext) -> list[Path]:
        spec = ctx.spec
        arch = spec.windows_arch
        out = ctx.outdir / f"{spec.file_stem}-{spec.version}-windows-{arch}-setup.exe"
        files = winstage.installed_files(ctx.stage)
        if UNINSTALLER in files:
            raise ValueError(f"the app contains its own {UNINSTALLER}, which the installer needs")
        payload_dir = ctx.workdir / "payload"
        payload_dir.mkdir()
        payload = {}
        for i, rel in enumerate(files):
            payload[rel] = payload_dir / f"{i:05d}"
            _link_or_copy(ctx.stage / rel, payload[rel])
        icon = payload.get(winstage.icon_name(spec))
        script = ctx.workdir / "installer.nsi"
        script.write_text(nsis_script(spec, payload, icon, out.resolve(), arch,
                                      winstage.installed_size_kib(ctx.stage)), encoding="utf-8")
        run(["makensis", "-V2", "-INPUTCHARSET", "UTF8", str(script)], ctx.log)
        return [out]
